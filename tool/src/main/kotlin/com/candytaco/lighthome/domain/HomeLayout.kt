/*
 * Screen models (rows, sections, destinations), the Home screen built from the user's dashboard
 * (cards: DashboardLayout.kt), and text versions of HA's generated area view and summary panels
 * (frontend src/panels/lovelace/strategies/home), used by area cards.
 */

// --- What the screens render ---

sealed interface Destination {
    data class Area(val areaId: String, val name: String) : Destination
    data class SummaryList(val summary: Summary) : Destination
    data object OtherDevices : Destination
    /** [title] is the name shown on the row that opened it, so the detail screen matches. */
    data class EntityDetail(val entityId: String, val title: String) : Destination

    /** A view (tab) of the user's dashboard. */
    data class View(val path: String, val title: String) : Destination

    /** Show this dashboard on Home ([urlPath] null = HA's default dashboard). */
    data class SelectDashboard(val urlPath: String?) : Destination

    // Settings actions
    data object ScanSetupCode : Destination
    data object EditServerUrl : Destination
    data object EditCfAccess : Destination
    data object RemoveCfAccess : Destination
    data object SignIn : Destination
    data object SignOut : Destination
}

sealed interface ListRow {
    val key: String

    /** An entity: name, then state (or the pending label while a command is in flight). */
    data class Entity(
        val entityId: String,
        val name: String,
        val value: String,
        val tapOpensDetail: Boolean,
        val longPressOpensDetail: Boolean,
    ) : ListRow {
        override val key get() = entityId
    }

    /** A row that opens another screen, e.g. "Lights  3 on" or "Kitchen  71°F". */
    data class Link(val label: String, val value: String, val destination: Destination) : ListRow {
        override val key get() = "link:$label"
    }

    /** Plain text, e.g. a markdown card's content. */
    data class Text(val text: String) : ListRow {
        override val key get() = "text:${text.hashCode()}"
    }

    /** A label and value that can't be tapped, e.g. "Connection  connected". */
    data class Info(val label: String, val value: String) : ListRow {
        override val key get() = "info:$label"
    }
}

data class ListSection(val title: String?, val rows: List<ListRow>)

/** Everything a list screen needs, captured at one moment. */
data class HomeSnapshot(
    val registry: Registry,
    val states: Map<String, EntityState>,
    val config: HomeConfig,
    /** Entity id to pending label, from the screen's commander. */
    val pending: Map<String, String>,
    /** The dashboard shown on Home and the dashboards to choose from. */
    val dashboardData: DashboardData = DashboardData(),
) {
    /** The selected dashboard's card config, once loaded. */
    val dashboard: JsonObject? get() = (dashboardData.state as? DashboardState.Loaded)?.config
}

/**
 * Home: the selected dashboard's cards. When it has no cards (auto-generated) or can't load,
 * that's stated instead; the dashboard is chosen in settings.
 */
fun HomeSnapshot.homeSections(): List<ListSection> {
    val data = dashboardData
    val title = data.selectedTitle
    dashboardViews(dashboard)?.let { return dashboardHomeSections(it) }
    val message = when (val state = data.state) {
        DashboardState.Loading -> "$title: load in progress…"
        DashboardState.AutoGenerated, is DashboardState.Loaded -> "$title: auto-generated, no cards"
        is DashboardState.Failed -> "$title: unavailable (${state.message})"
    }
    return listOf(ListSection(null, listOf(ListRow.Text(message))))
}

/** Every dashboard, the one on Home marked "current". */
internal fun dashboardRows(data: DashboardData): List<ListRow> = data.dashboards.map { dashboard ->
    ListRow.Link(
        label = dashboard.title,
        value = if (dashboard.urlPath == data.selectedPath) "current" else "",
        destination = Destination.SelectDashboard(dashboard.urlPath),
    )
}

// --- Summaries: entity filters and one-line text, as in hui-home-summary-card ---

enum class Summary(val key: String, val title: String) {
    Light("light", "Lights"),
    Climate("climate", "Climate"),
    Security("security", "Security"),
    MediaPlayers("media_players", "Media"),
    Maintenance("maintenance", "Maintenance"),
    ;

    companion object {
        fun byKey(key: String): Summary? = entries.firstOrNull { it.key == key }
    }
}

/** HA EntityFilter: domain, optional device classes (null in the set = no device class), entity category. */
private data class EntityFilter(
    val domain: String,
    val deviceClasses: Set<String?>? = null,
    val diagnostic: Boolean = false,
)

private val SUMMARY_FILTERS: Map<Summary, List<EntityFilter>> = mapOf(
    Summary.Light to listOf(EntityFilter("light")),
    Summary.Climate to listOf(
        EntityFilter("climate"),
        EntityFilter("humidifier"),
        EntityFilter("fan"),
        EntityFilter("water_heater"),
        EntityFilter("cover", setOf("awning", "blind", "curtain", "shade", "shutter", "window", null)),
        EntityFilter("binary_sensor", setOf("window")),
    ),
    Summary.Security to listOf(
        EntityFilter("camera"),
        EntityFilter("alarm_control_panel"),
        EntityFilter("lock"),
        EntityFilter("cover", setOf("door", "garage", "gate", "window")),
        EntityFilter(
            "binary_sensor",
            setOf(
                "lock", "door", "window", "garage_door", "opening", "carbon_monoxide", "gas",
                "glass_break", "moisture", "safety", "smoke", "tamper",
            ),
        ),
        EntityFilter("binary_sensor", setOf("tamper"), diagnostic = true),
    ),
    Summary.MediaPlayers to listOf(EntityFilter("media_player")),
    Summary.Maintenance to listOf(
        EntityFilter("sensor", setOf("battery")),
        EntityFilter("binary_sensor", setOf("battery")),
    ),
)

private fun EntityState.deviceClass(): String? = attributes.string("device_class")

private fun EntityFilter.matches(entity: EntityState, registry: Registry): Boolean {
    if (entity.domain != domain) return false
    if (deviceClasses != null && entity.deviceClass() !in deviceClasses) return false
    val category = registry.entry(entity.entityId)?.entityCategory
    return if (diagnostic) category == "diagnostic" else category == null
}

private fun HomeSnapshot.visible(): List<EntityState> = states.values.filter { registry.isVisible(it.entityId) }

fun HomeSnapshot.summaryEntities(summary: Summary): List<EntityState> {
    val filters = SUMMARY_FILTERS.getValue(summary)
    return visible().filter { entity -> filters.any { it.matches(entity, registry) } }
}

/** The summary's one-line state; null when there's nothing to summarize (HA hides the card). */
fun HomeSnapshot.summaryText(summary: Summary): String? {
    val entities = summaryEntities(summary)
    return when (summary) {
        Summary.Light -> if (entities.isEmpty()) null else {
            val on = entities.count { it.state == "on" }
            if (on > 0) "$on on" else "all off"
        }
        Summary.Climate -> climateText(entities)
        Summary.Security -> securityText(entities)
        Summary.MediaPlayers -> if (entities.isEmpty()) null else {
            val playing = entities.count { it.state == "playing" }
            if (playing > 0) "$playing playing" else "none playing"
        }
        Summary.Maintenance -> if (entities.isEmpty()) null else maintenanceText(entities)
    }
}

/** Range of the areas' temperature sensors; falls back to "N devices" when no area has one. */
private fun HomeSnapshot.climateText(entities: List<EntityState>): String? {
    val temperatures = registry.areas.mapNotNull { area ->
        area.temperatureEntityId?.let { states[it]?.state?.toDoubleOrNull() }
    }
    if (temperatures.isNotEmpty()) {
        val min = formatNumber(temperatures.min())
        val max = formatNumber(temperatures.max())
        return if (min == max) "$min°" else "$min–$max°"
    }
    return if (entities.isEmpty()) null else "${entities.size} devices"
}

private fun securityText(entities: List<EntityState>): String? {
    val locks = entities.filter { it.domain == "lock" }
    val alarms = entities.filter { it.domain == "alarm_control_panel" }
    if (locks.isEmpty() && alarms.isEmpty()) return null
    val unlocked = locks.count { it.state in setOf("unlocked", "jammed", "open") }
    val disarmed = alarms.count { it.state == "disarmed" }
    return when {
        unlocked > 0 -> "$unlocked unlocked"
        disarmed > 0 -> "$disarmed disarmed"
        else -> "all secure"
    }
}

private const val LOW_BATTERY_PERCENT = 20.0

private fun HomeSnapshot.maintenanceText(batteries: List<EntityState>): String {
    val low = lowBatteries(batteries).size
    val unavailable = batteries.count { it.state == "unavailable" }
    val parts = listOfNotNull(
        low.takeIf { it > 0 }?.let { "$it low battery" },
        unavailable.takeIf { it > 0 }?.let { "$it unavailable" },
    )
    return if (parts.isEmpty()) "all good" else parts.joinToString(", ")
}

/** Battery sensors at or below 20 % (or battery binary sensors on), skipping devices that are charging. */
private fun HomeSnapshot.lowBatteries(batteries: List<EntityState>): List<EntityState> {
    val chargingDevices = states.values
        .filter { it.domain == "binary_sensor" && it.deviceClass() == "battery_charging" && it.state == "on" }
        .mapNotNull { registry.entry(it.entityId)?.deviceId }
        .toSet()
    return batteries.filter { battery ->
        val low = if (battery.domain == "binary_sensor") {
            battery.state == "on"
        } else {
            battery.state.toDoubleOrNull()?.let { it <= LOW_BATTERY_PERCENT } ?: false
        }
        low && registry.entry(battery.entityId)?.deviceId !in chargingDevices
    }
}

// --- Rows ---

private fun HomeSnapshot.entityRow(entity: EntityState, namePrefix: String?) = ListRow.Entity(
    entityId = entity.entityId,
    name = registry.entityDisplayName(entity, namePrefix),
    value = pending[entity.entityId] ?: formatState(entity),
    tapOpensDetail = tapOpensDetail(entity),
    longPressOpensDetail = longPressOpensDetail(entity),
)

private fun HomeSnapshot.entityRows(entities: List<EntityState>, namePrefix: String?): List<ListRow> =
    entities
        .sortedBy { registry.entityDisplayName(it, namePrefix).lowercase() }
        .map { entityRow(it, namePrefix) }

// --- Area (home-area-view-strategy) ---

private val AREA_SUMMARIES = listOf(Summary.Light, Summary.Climate, Summary.Security, Summary.MediaPlayers)

fun HomeSnapshot.areaSections(areaId: String): List<ListSection> {
    val area = registry.areasById[areaId] ?: return emptyList()
    val inArea = visible().filter { registry.areaIdOf(it.entityId) == areaId }
    val used = mutableSetOf<String>()
    val sections = mutableListOf<ListSection>()

    // The area's primary sensors (HA shows them as header badges).
    val sensors = listOfNotNull(area.temperatureEntityId, area.humidityEntityId).mapNotNull { states[it] }
    if (sensors.isNotEmpty()) sections += ListSection(null, sensors.map { entityRow(it, area.name) })

    AREA_SUMMARIES.forEach { summary ->
        val filters = SUMMARY_FILTERS.getValue(summary)
        val members = inArea.filter { e -> e.entityId !in used && filters.any { it.matches(e, registry) } }
        used += members.map { it.entityId }
        if (members.isNotEmpty()) sections += ListSection(summary.sectionTitle(), entityRows(members, area.name))
    }

    val scenes = inArea.filter { it.domain == "scene" && it.entityId !in used && registry.isPrimary(it.entityId) }
    used += scenes.map { it.entityId }
    if (scenes.isNotEmpty()) sections += ListSection("Scenes", entityRows(scenes, area.name))

    val automations = inArea.filter { it.domain == "automation" && it.entityId !in used && registry.isPrimary(it.entityId) }
    used += automations.map { it.entityId }

    val rest = inArea.filter { it.entityId !in used && registry.isPrimary(it.entityId) }
    sections += deviceSections(rest, othersTitle = "Others")

    if (automations.isNotEmpty()) sections += ListSection("Automations", entityRows(automations, area.name))
    return sections
}

private fun Summary.sectionTitle() = if (this == Summary.MediaPlayers) "Media players" else title

/**
 * One section per device, titled with the device name and its battery level ("Front Door · 80%");
 * battery sensors themselves aren't listed. Entities without a device come last under [othersTitle].
 */
private fun HomeSnapshot.deviceSections(entities: List<EntityState>, othersTitle: String): List<ListSection> {
    val byDevice = entities.groupBy { registry.entry(it.entityId)?.deviceId }
    val withDevice = byDevice.entries.filter { it.key != null }.mapNotNull { (deviceId, members) ->
        val device = registry.device(deviceId)
        val name = device?.displayName ?: "Unnamed device"
        val battery = members.firstOrNull { it.domain == "sensor" && it.deviceClass() == "battery" }
        val shown = members.filter { !(it.domain == "sensor" && it.deviceClass() == "battery") }
        if (shown.isEmpty()) return@mapNotNull null
        val title = battery?.let { "$name · ${formatState(it)}" } ?: name
        ListSection(title, entityRows(shown, device?.displayName))
    }.sortedBy { it.title?.lowercase() }
    val others = byDevice[null]?.let { ListSection(othersTitle, entityRows(it, null)) }
    return withDevice + listOfNotNull(others)
}

// --- Summary panels (light / climate / security / media / maintenance views) ---

/** The summary's entities grouped by area in floor-then-area order, then those without an area. */
fun HomeSnapshot.summarySections(summary: Summary): List<ListSection> {
    val entities = summaryEntities(summary)
    val byArea = entities.groupBy { registry.areaIdOf(it.entityId) }
    val knownFloors = registry.floors.map { it.floorId }.toSet()
    val areaOrder = registry.floors.flatMap { floor -> registry.areas.filter { it.floorId == floor.floorId } } +
        registry.areas.filter { it.floorId == null || it.floorId !in knownFloors }

    val sections = areaOrder.mapNotNull { area ->
        byArea[area.areaId]?.let { ListSection(area.name, entityRows(it, area.name)) }
    }
    val unassigned = byArea[null]?.let {
        ListSection(if (sections.isEmpty()) null else "Other ${summary.title.lowercase()}", entityRows(it, null))
    }
    return sections + listOfNotNull(unassigned)
}

// --- Devices without an area (home-other-devices-view-strategy) ---

private fun HomeSnapshot.otherDeviceEntities(): List<EntityState> = visible().filter { entity ->
    val entry = registry.entry(entity.entityId) ?: return@filter false
    val device = registry.device(entry.deviceId) ?: return@filter false
    entry.areaId == null && device.areaId == null && entry.entityCategory == null
}

fun HomeSnapshot.otherDevicesSections(): List<ListSection> = deviceSections(otherDeviceEntities(), othersTitle = "Others")
